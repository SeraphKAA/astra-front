import React from "react";
import { useLocation } from "react-router-dom";
import "./pageFade.css";

/**
 * PageFade — короткий фейд входящей страницы при смене маршрута.
 *
 * История двух отвергнутых вариантов, чтобы их не изобрели заново:
 *  1) держать уходящее дерево смонтированным в другой обёртке — React
 *     считает это новым узлом и монтирует страницу заново: у покидаемой
 *     страницы повторно отрабатывали эффекты и уходили лишние запросы;
 *  2) гасить КЛОН разметки (innerHTML) — из-за key на живом контейнере
 *     снимок жил на узле, который React только что выбросил, поэтому
 *     кросс-фейд не запускался НИ РАЗУ, а каждая навигация сериализовала
 *     ~70КБ разметки в data-атрибут. Мёртвый код с ценой.
 *
 * Осталось честное: входящая страница коротко проявляется. Уходящей
 * анимации нет — и её отсутствие не притворяется работающим механизмом.
 */
const PageFade = ({ children }) => {
    const location = useLocation();
    return (
        <div className="fx-pagefade">
            <div className="fx-pagefade-in" key={location.pathname}>
                {children}
            </div>
        </div>
    );
};

export default PageFade;
